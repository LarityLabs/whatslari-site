const approvedAudio = {
  'crt-power-on.mp3': 'B56E82914D97659E61917CD64E7EAB20685FCC1C5D6E58A430DEEAF8F871F049',
  'dialup-connect.mp3': '0BE40A5E8ADDBCFEE473861C687F0F2A6DB798A1016320FD6B3B71AC948DF549'
};
for (const [audio, expectedHash] of Object.entries(approvedAudio)) {
  await fs.access(path.join(root, 'assets', audio));
  await fs.access(path.join(root, 'dist/assets', audio));
  for (const location of [path.join(root, 'assets', audio), path.join(root, 'dist/assets', audio)]) {
    const bytes = await fs.readFile(location);
    assert.equal(crypto.createHash('sha256').update(bytes).digest('hex').toUpperCase(), expectedHash, `${audio} must remain the approved unmodified recording`);
  }
  assert.doesNotMatch(home, /autoplay/i, 'startup audio must not autoplay');
}
