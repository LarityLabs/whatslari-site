import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { validateSnapshot, scanPublicText } from './data-schema.mjs';

const root = path.resolve(process.env.LARI_SITE_ROOT || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));
const snapshotId = process.argv[2];
const reason = process.argv.slice(3).join(' ').trim();
if (!/^snapshot-\d{14}$/.test(snapshotId || '')) throw new Error('Usage: npm run research:rollback -- snapshot-YYYYMMDDhhmmss "reason"');
if (reason.length < 12) throw new Error('Provide a private rollback reason of at least 12 characters.');
const approvedDir = path.join(root, 'data/approved');
const previousPath = path.join(approvedDir, 'history', `${snapshotId}.json`);
const currentPath = path.join(approvedDir, 'snapshot.json');
const previousText = await fs.readFile(previousPath, 'utf8');
const previous = JSON.parse(previousText);
const issues = [...validateSnapshot(previous), ...scanPublicText(previous)];
if (issues.length || previous.status !== 'approved' || previous.snapshotId !== snapshotId) throw new Error(`Rollback target is not a valid approved snapshot:\n- ${issues.join('\n- ') || 'snapshot identity/status mismatch'}`);
const currentText = await fs.readFile(currentPath, 'utf8');
const current = JSON.parse(currentText);
const currentIssues = [...validateSnapshot(current), ...scanPublicText(current)];
if (currentIssues.length || current.status !== 'approved') throw new Error(`Current public snapshot is invalid; rollback stopped:\n- ${currentIssues.join('\n- ') || 'current snapshot is not approved'}`);
const currentHistoryPath = path.join(approvedDir, 'history', `${current.snapshotId}.json`);
const archivedCurrent = await fs.readFile(currentHistoryPath, 'utf8').catch(() => null);
if (archivedCurrent && JSON.stringify(JSON.parse(archivedCurrent)) !== JSON.stringify(current)) throw new Error(`History already contains different content for ${current.snapshotId}; refusing to overwrite it.`);
if (!archivedCurrent) await fs.writeFile(currentHistoryPath, `${JSON.stringify(current, null, 2)}\n`, 'utf8');
await fs.writeFile(currentPath, previousText, 'utf8');
const logPath = path.join(root, 'private-review/rollback-log.jsonl');
await fs.mkdir(path.dirname(logPath), { recursive: true });
const sha256 = crypto.createHash('sha256').update(previousText).digest('hex');
await fs.appendFile(logPath, `${JSON.stringify({ schemaVersion: 1, rolledBackAt: new Date().toISOString(), restoredSnapshotId: previous.snapshotId, previousCurrentSnapshotId: current.snapshotId, restoredFileSha256: sha256, reason, publicPublishPerformed: false })}\n`, 'utf8');
process.stdout.write(`Restored approved snapshot ${previous.snapshotId}; archived ${current.snapshotId}. No remote publication was performed.\n`);
